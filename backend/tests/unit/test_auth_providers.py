"""
Unit tests for DevAuthProvider and ClerkAuthProvider.
Adheres strictly to Spec §3.2, §3.5, §7, §9.1.
Uses local offline JWKSHelper for RSA key generation and JWT signing.
"""
from __future__ import annotations

import httpx
import pytest
from backend.app.domain.errors import AuthenticationError
from backend.app.domain.interfaces import IAuthProvider
from backend.app.infrastructure.auth.clerk import ClerkAuthProvider
from backend.app.infrastructure.auth.dev import DevAuthProvider
from backend.test_support.jwks_helper import JWKSHelper


def test_protocol_conformance():
    dev_auth = DevAuthProvider()
    assert isinstance(dev_auth, IAuthProvider)

    clerk_auth = ClerkAuthProvider(
        jwks_url="https://clerk.example.com/.well-known/jwks.json",
        issuer="https://clerk.example.com",
    )
    assert isinstance(clerk_auth, IAuthProvider)


@pytest.mark.asyncio
async def test_dev_auth_provider():
    auth = DevAuthProvider()
    # Any request returns user_dev_001
    user = await auth.authenticate(request={})
    assert user.id == "user_dev_001"
    assert user.username == "dev_user"
    assert user.email == "dev@example.com"

    user2 = await auth.authenticate(request=None)
    assert user2.id == "user_dev_001"


@pytest.fixture
def jwks_setup():
    helper = JWKSHelper(kid="test-key-1", issuer="https://clerk.test")
    jwks_data = helper.get_jwks()

    # Mock HTTP transport serving the JWKS
    def handler(request: httpx.Request) -> httpx.Response:
        if request.url.path.endswith("/jwks.json"):
            return httpx.Response(200, json=jwks_data)
        return httpx.Response(404)

    transport = httpx.MockTransport(handler)
    client = httpx.AsyncClient(transport=transport)
    auth = ClerkAuthProvider(
        jwks_url="https://clerk.test/.well-known/jwks.json",
        issuer="https://clerk.test",
        client=client,
    )
    return helper, auth


@pytest.mark.asyncio
async def test_clerk_auth_bearer_token(jwks_setup):
    helper, auth = jwks_setup
    token = helper.generate_token(
        user_id="user_alice",
        email="alice@example.com",
        username="alice",
    )

    request = {"headers": {"Authorization": f"Bearer {token}"}}
    user = await auth.authenticate(request)
    assert user.id == "user_alice"
    assert user.email == "alice@example.com"
    assert user.username == "alice"


@pytest.mark.asyncio
async def test_clerk_auth_query_param_token(jwks_setup):
    """Spec §3.5: Browsers cannot set WebSocket headers, so token goes in query string."""
    helper, auth = jwks_setup
    token = helper.generate_token(
        user_id="user_bob",
        email="bob@example.com",
    )

    request = {"headers": {}, "query_params": {"token": token}}
    user = await auth.authenticate(request)
    assert user.id == "user_bob"
    assert user.email == "bob@example.com"


