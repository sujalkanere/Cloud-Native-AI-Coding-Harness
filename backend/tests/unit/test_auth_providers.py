@pytest.mark.asyncio
async def test_clerk_auth_untrusted_signature(jwks_setup):
    _, auth = jwks_setup
    # Token generated by a DIFFERENT untrusted helper with different RSA key
    untrusted_helper = JWKSHelper(kid="test-key-1", issuer="https://clerk.test")
    token = untrusted_helper.generate_token(user_id="attacker")

    request = {"headers": {"Authorization": f"Bearer {token}"}}
    with pytest.raises(AuthenticationError, match="Invalid token signature"):
        await auth.authenticate(request)


